"""Pass-and-swap service as (truncated) promotion on linear extensions.

Certificate: promotion_check.json.  Standard library only; deterministic.
Run:  python3 -S -O promotion_check.py

Let W be the global word (upper queue followed by the reversed lower queue)
and P_A the partial order generated by its placement orientation A.  For a
position i let tau_i exchange W[i] and W[i+1] when they are incomparable in
P_A and do nothing otherwise.  The paper's Proposition "promotion" states:
  (a) uncapped service of the job in position p of the upper queue (k jobs)
      maps W to tau_{k-1} ... tau_{p+1} tau_p W (tau_p applied first);
      for p = 0, k = n this is Schuetzenberger promotion of W;
  (b) capped service is the same bubble sort truncated at the w-th
      comparable encounter: the element carried at that moment is moved to
      position k-1 regardless of comparabilities;
  (c) lower-queue service is the mirror image (reverse W, exchange queues);
  (d) on C_{2w+1}, the capped head map from the full upper queue, encoded
      as a binary word (source fixed; first bit = which of the two balanced
      orientations, then the long/short letters, complemented for the
      second orientation), is cyclic left rotation (w = 2..6, both
      labellings of the two orientations).
(a)-(c) are checked on every state, position and cap of every graph on at
most 5 vertices and of C6, K6, K33 and two triangles joined by an edge; (d) on every balanced full word for w = 2..6.
"""
import hashlib
import json
from itertools import combinations, permutations
from pathlib import Path

HERE = Path(__file__).resolve().parent

def check(cond, msg):
    if not cond:
        raise RuntimeError(msg)


def dump(payload):
    """Deterministic JSON: one top-level key per line, compact values."""
    return '{\n' + ',\n'.join(json.dumps(k) + ': ' + json.dumps(payload[k], sort_keys=True, separators=(',', ':'))
                              for k in sorted(payload)) + '\n}\n'


def refine(n, adj):
    col = [0] * n
    while True:
        sig = [(col[v], tuple(sorted(col[u] for u in range(n) if adj[v] >> u & 1)))
               for v in range(n)]
        keys = sorted(set(sig))
        new = [keys.index(s) for s in sig]
        if len(set(new)) == len(set(col)):
            return new
        col = new


def canon(n, adj):
    """Canonical code: minimum upper-triangle bit code over all labellings
    that respect the (isomorphism-invariant) colour-refinement order."""
    col = refine(n, adj)
    classes = {}
    for v in range(n):
        classes.setdefault(col[v], []).append(v)
    groups = [classes[c] for c in sorted(classes)]

    def seqs(i):
        if i == len(groups):
            yield []
            return
        for p in permutations(groups[i]):
            for rest in seqs(i + 1):
                yield list(p) + rest
    best = None
    for seq in seqs(0):
        code = 0
        bit = 0
        for i in range(n):
            ai = adj[seq[i]]
            for j in range(i + 1, n):
                if ai >> seq[j] & 1:
                    code |= 1 << bit
                bit += 1
        if best is None or code < best:
            best = code
    return best


def decode(n, code):
    adj = [0] * n
    bit = 0
    for i in range(n):
        for j in range(i + 1, n):
            if code >> bit & 1:
                adj[i] |= 1 << j
                adj[j] |= 1 << i
            bit += 1
    return adj


def all_graphs(nmax):
    levels = {1: [0]}
    for n in range(2, nmax + 1):
        seen = set()
        for code in levels[n - 1]:
            base = decode(n - 1, code)
            for mask in range(1 << (n - 1)):
                adj = base[:] + [mask]
                for u in range(n - 1):
                    if mask >> u & 1:
                        adj[u] |= 1 << (n - 1)
                seen.add(canon(n, adj))
        levels[n] = sorted(seen)
    return levels


def capped_transfer(source, position, adj, w):
    """Serve source[position]; at most w carrier replacements; return
    (new source tuple, departing job).  Direct implementation of the rule."""
    out = list(source)
    carried = source[position]
    loc = position
    for _ in range(w):
        nxt = None
        for j in range(loc + 1, len(source)):
            if adj[carried] >> source[j] & 1:
                nxt = j
                break
        if nxt is None:
            break
        out[nxt] = carried
        carried = source[nxt]
        loc = nxt
    del out[position]
    return tuple(out), carried




def comparable_matrix(word, adj):
    n = len(word)
    pos = {v: i for i, v in enumerate(word)}
    less = {v: 0 for v in word}           # bitmask of elements below v
    for v in word:
        m = 0
        for u in word[:pos[v]]:
            if adj[v] >> u & 1:
                m |= less[u] | (1 << u)
        less[v] = m
    def comp(a, b):
        return bool(less[a] >> b & 1 or less[b] >> a & 1)
    return comp


def bubble(word, p, k, comp, cap=None):
    """Apply tau_p, tau_{p+1}, ..., tau_{k-2} (0-indexed: exchange positions
    i, i+1 for i = p..k-2).  With a cap: after the cap-th comparable
    encounter the carried element is moved to position k-1."""
    W = list(word)
    i = p
    hits = 0
    while i < k - 1:
        if comp(W[i], W[i + 1]):
            hits += 1
            if cap is not None and hits == cap:
                # element now carried is W[i+1]; move it to position k-1
                x = W.pop(i + 1)
                W.insert(k - 1, x)
                return tuple(W)
        else:
            W[i], W[i + 1] = W[i + 1], W[i]
        i += 1
    return tuple(W)


def balanced_full_words(w):
    n = 2 * w + 1
    out = []
    for s in range(n):
        for sign in (1, -1):
            long_ = [(s + sign * j) % n for j in range(1, w + 1)]
            short = [(s - sign * j) % n for j in range(1, w)]
            t = (s + sign * (w + 1)) % n
            for pos in combinations(range(2 * w - 1), w):
                ps = set(pos)
                inner = []
                ix = iy = 0
                for j in range(2 * w - 1):
                    if j in ps:
                        inner.append(long_[ix])
                        ix += 1
                    else:
                        inner.append(short[iy])
                        iy += 1
                out.append(tuple([s] + inner + [t]))
    return out


def code(word, w, flip):
    n = 2 * w + 1
    s, t = word[0], word[-1]
    sign = 1 if (t - s) % n == w + 1 else -1
    eps = (0 if sign == 1 else 1) ^ flip
    longset = {(s + sign * j) % n for j in range(1, w + 1)}
    letters = [1 if v in longset else 0 for v in word[1:-1]]
    if eps == 1:
        letters = [1 - x for x in letters]
    return tuple([eps] + letters)


def main():
    levels = all_graphs(5)
    tests = [(n, decode(n, g)) for n in range(2, 6) for g in levels[n]]
    def adj_of(n, el):
        a = [0] * n
        for u, v in el:
            a[u] |= 1 << v
            a[v] |= 1 << u
        return a
    extra = {'C6': [(i, (i + 1) % 6) for i in range(6)],
             'K6': [(i, j) for i in range(6) for j in range(i + 1, 6)],
             'two triangles and a bridge': [(0, 1), (1, 2), (0, 2), (0, 3), (3, 4), (4, 5), (3, 5)],
             'K33': [(i, j) for i in range(3) for j in range(3, 6)]}
    tests += [(6, adj_of(6, el)) for el in extra.values()]
    checked = 0
    for n, adj in tests:
        if True:
            for perm in permutations(range(n)):
                comp = comparable_matrix(perm, adj)
                for k in range(n + 1):
                    c = perm[:k]
                    d = tuple(reversed(perm[k:]))
                    for p in range(k):
                        for w in list(range(1, n)) + [n]:      # w = n: no binding possible (uncapped)
                            nc, dep = capped_transfer(c, p, adj, w)
                            newword = nc + (dep,) + perm[k:]
                            pred = bubble(perm, p, k, comp, None if w == n else w)
                            check(newword == pred, f'upper promotion identity fails n={n}')
                            checked += 1
                    # lower queue: mirror
                    rword = tuple(reversed(perm))
                    rcomp = comparable_matrix(rword, adj)
                    for p in range(len(d)):
                        for w in list(range(1, n)) + [n]:
                            nd, dep = capped_transfer(d, p, adj, w)
                            newword = c + (dep,) + tuple(reversed(nd))
                            pred = tuple(reversed(bubble(rword, p, n - k, rcomp, None if w == n else w)))
                            check(newword == pred, f'lower promotion identity fails n={n}')
                            checked += 1
    rot = []
    for w in range(2, 7):
        n = 2 * w + 1
        adj = [(1 << ((v + 1) % n)) | (1 << ((v - 1) % n)) for v in range(n)]
        words = balanced_full_words(w)
        check(len(set(words)) == len(words), 'duplicate words')
        for flip in (0, 1):
            for W in words:
                nc, dep = capped_transfer(W, 0, adj, w)
                W2 = nc + (dep,)
                check(W2[0] == W[0], 'source should be fixed by the head map')
                c1 = code(W, w, flip)
                check(code(W2, w, flip) == c1[1:] + c1[:1], 'not a cyclic rotation')
        rot.append({'w': w, 'balanced_full_words': len(words), 'rotation_holds_both_labellings': True})
    payload = {
        'status': 'PASS',
        'promotion_identity_checks': checked,
        'graphs': 'all graphs on 2..5 vertices, and on 6 vertices: ' + ', '.join(sorted(extra)),
        'binary_rotation': rot,
        'input_sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        'verifier': Path(__file__).name,
    }
    (HERE / 'promotion_check.json').write_text(dump(payload))
    print(json.dumps({'status': 'PASS', 'promotion_identity_checks': checked}))


if __name__ == '__main__':
    main()
